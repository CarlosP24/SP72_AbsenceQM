# Data of the interactive figures of the web talk (slides/quarto), exported as JavaScript
# files assets/data/<name>.js, each setting QMD.<name>, so that the deck runs from file://
# without a server. Heat maps are quantized to 8 bits over a fixed colour range and stored
# as base64, x index fastest.
#
# Sources: the published data in data/ (read with the helpers of slides/make_figs.jl, which
# this file includes), data_unpublished/PD_mu_flux (as the poster, it only adds the
# all-trivial region below 21 meV), data/E_QMZM (hidden quasi-MZM energy, computed for the
# poster), and the illustrative talk calculations in slides/data/. No result of the paper
# is recomputed here.
#
# Run from anywhere (plots environment, through make_figs.jl):
#   julia slides/quarto/julia/export_data.jl [name ...]      (no names: everything)

