# Published (quasi-)MZM densities along the wire, each normalised to its maximum
EXPORTS["wfs"] = function ()
    out = Dict{String, Any}()
    for (shell, name, χ, step) in (("partial", "base_partial", 200, 1), ("full", "base_fs", 1000, 4))
        Ψs = loadres("data/wfs/$(name).jld2").Psis
        d = Dict{String, Any}()
        for key in ("Majo", "QMajo")
            ΨL, ΨR = Ψs[key]
            z = collect(0:length(ΨL)-1) .* 5 ./ χ
            k = findall(z .<= 14)
            k = k[1:step:end]
            d[key] = (; z = z[k], L = ΨL[k] ./ maximum(ΨL), R = ΨR[k] ./ maximum(ΨR))
        end
        out[shell] = d
    end
    write_js("wfs", out; note = "data/wfs/{base_partial,base_fs}.jld2, z in units of χ (200 nm, 1 µm), " *
        "each density normalised to its own maximum (paper ref. [83]).")
end

