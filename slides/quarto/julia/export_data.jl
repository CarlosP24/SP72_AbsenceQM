## ---------------------------------------------------------------------------
## Minimal JSON writer
## ---------------------------------------------------------------------------
struct Raw
    s::String
end
jesc(s) = replace(s, "\\" => "\\\\", "\"" => "\\\"", "\n" => "\\n")
js(x::Raw) = x.s
js(x::AbstractString) = "\"" * jesc(x) * "\""
js(x::Symbol) = js(string(x))
js(x::Bool) = x ? "true" : "false"
js(x::Integer) = string(x)
js(x::Real) = isfinite(x) ? string(round(Float64(x); sigdigits = 5)) : "null"
js(::Nothing) = "null"
js(x::Union{AbstractVector, Tuple}) = "[" * join((js(v) for v in x), ",") * "]"
js(x::AbstractDict) = "{" * join((js(string(k)) * ":" * js(v) for (k, v) in x), ",") * "}"
js(x::NamedTuple) = "{" * join((js(string(k)) * ":" * js(v) for (k, v) in pairs(x)), ",") * "}"

function write_js(name, obj; note = "")
    mkpath(OUT)
    path = joinpath(OUT, "$(name).js")
    open(path, "w") do io
        println(io, "// Generated by slides/quarto/julia/export_data.jl. ", note)
        println(io, "window.QMD = window.QMD || {};")
        println(io, "QMD[\"$(name)\"] = ", js(obj), ";")
    end
    println("  ", name, ".js  ", round(filesize(path) / 1024; digits = 1), " kB")
end

# 8-bit heat map over (lo, hi), clipped; M is nx × ny (x fastest in the output)
function q8(M, lo, hi)
    A = clamp.((M .- lo) ./ (hi - lo), 0, 1)
    A = replace(A, NaN => 0.0)
    return (nx = size(M, 1), ny = size(M, 2), lo = lo, hi = hi,
        b64 = Raw(js(base64encode(vec(round.(UInt8, 255 .* A))))))
end

# Intervals of a phase-diagram column where `istopo` holds, at the midpoints of the flips
function intervals(ys, col; istopo = ==(1))
    t = [!isnan(c) && istopo(c) for c in col]
    out = Vector{Vector{Float64}}()
    i = 1
    while i <= length(t)
        if t[i]
            j = i
            while j < length(t) && t[j+1]
                j += 1
            end
            a = i == 1 ? ys[1] : (ys[i-1] + ys[i]) / 2
            b = j == length(t) ? ys[end] : (ys[j] + ys[j+1]) / 2
            push!(out, [a, b])
            i = j + 1
        else
            i += 1
        end
    end
    return out
end

downsample(v, k) = v[1:k:end]

