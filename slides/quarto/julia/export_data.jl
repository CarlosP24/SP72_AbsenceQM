# Partial-shell phase diagram (V_Z/V_Z^c, μ/μ_bulk): topological μ interval per V_Z
EXPORTS["pd_partial"] = function ()
    res = loadres("data/PD_mu_B/base_partial.jld2")
    cp = res.system.calc_params
    VZ = collect(cp.Brng) ./ VZc
    μ = collect(cp.μrngP) ./ 2
    keep = findall(VZ .<= 2.05)
    iv = [intervals(μ, res.PD[:, j]) for j in keep]
    write_js("pd_partial", (; VZ = VZ[keep], iv);
        note = "data/PD_mu_B/base_partial.jld2: topological μ/μ_bulk intervals at each V_Z/V_Z^c.")
end

# Full-shell phase diagram (Φ/Φ0, μ/μ_bulk) in lobe 1: topological intervals per Φ
EXPORTS["pd_full"] = function ()
    r = loadres("data/PD_mu_flux/base_fs_zoom.jld2")
    Φs, μz_, PDz = collect(r.system.calc_params.Φrng_PD), collect(r.system.calc_params.μrng), r.PD
    rc = loadres("data_unpublished/PD_mu_flux/base_fs.jld2")
    μc_, PDc = collect(rc.system.calc_params.μrng), rc.PD
    iv = map(eachindex(Φs)) do j
        fine = intervals(μz_, view(PDz, :, j); istopo = ==(-1))
        coarse = filter(ab -> ab[2] < first(μz_) || ab[1] > last(μz_),
            intervals(μc_, view(PDc, :, j); istopo = ==(-1)))
        [ab ./ μbulkF for ab in vcat(coarse, fine)]
    end
    write_js("pd_full", (; Φ = Φs, iv, μts = PH.μts, w = 0.005);
        note = "data/PD_mu_flux/base_fs_zoom.jld2 (21–24 meV) on data_unpublished/PD_mu_flux/base_fs.jld2: " *
               "topological μ/μ_bulk intervals at each Φ/Φ0 (lobe 1). μts and w define the schematic μ axis.")
end

